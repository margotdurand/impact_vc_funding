# Convert Boolean Columns to Integers (to avoid OLS errors)
bool_cols = X.select_dtypes(include='bool').columns
X[bool_cols] = X[bool_cols].astype(int)

# Add Constant Term (Intercept)
X = sm.add_constant(X)

# Estimate the OLS Model with Robust Standard Errors (HC3)
