"""### Model 3: Full specification with controls"""

# Dependent Variable
y = np.log(df_final["post_round_company_valuation"])

# Main Independent Variables
X_funding = np.log(df_final["company_total_funding"])
X_investors = df_final["number_of_investors"]

# Construct Company Age as a Control Variable
df_final["company_age"] = (
    pd.to_datetime(df_final["investment_date"]).dt.year
    - pd.to_datetime(df_final["company_founded_date"]).dt.year
).clip(lower=0)  # Set negative values to 0

# Additional Controls at the Fund Level (log-transformed to avoid tiny coefficients)
fund_size = np.log(df_final["fund_size_max"].replace(0, np.nan))  # avoid log(0)
fund_deals = np.log(df_final["fund_deals_max"].replace(0, np.nan))

# Drop rows with NaN values resulting from log(0)
mask = (~fund_size.isna()) & (~fund_deals.isna())
y = y[mask]
X_funding = X_funding[mask]
X_investors = X_investors[mask]
df_final_filtered = df_final.loc[mask]
fund_size = fund_size[mask]
fund_deals = fund_deals[mask]

# Interaction Term: log(funding) × region
interaction = X_funding * df_final_filtered["EU_region"]

# Build X DataFrame Including All Variables
X = pd.DataFrame({
    "log_funding": X_funding,
    "EU_region": df_final_filtered["EU_region"],
    "interaction": interaction,
    "num_investors": X_investors,
    "company_age": df_final_filtered["company_age"],
    "fund_size": fund_size,
    "fund_deals": fund_deals,
    "industry": df_final_filtered["company_industry"],
    "year": pd.to_datetime(df_final_filtered["investment_date"]).dt.year
})

# Add Industry Fixed Effects
X = pd.get_dummies(X, columns=["industry"], drop_first=True)

# Add Year Fixed Effects
