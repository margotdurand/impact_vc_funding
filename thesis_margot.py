"""### 3. Endogeneity tests"""

# prepare cleaned dataframe
df_iv = df_final.copy()

# create logged variables
df_iv["log_valuation"] = np.log(df_iv["post_round_company_valuation"])
df_iv["log_funding"] = np.log(df_iv["company_total_funding"])

# clean instruments and drop missing
df_iv["fund_size_max"] = df_iv["fund_size_max"].replace([np.inf, -np.inf], np.nan)
df_iv["fund_deals_max"] = df_iv["fund_deals_max"].replace([np.inf, -np.inf], np.nan)
df_iv = df_iv.dropna(subset=["log_valuation", "log_funding", "fund_size_max", "fund_deals_max"])

# Fit OLS using same dataframe
ols = IV2SLS.from_formula("log_valuation ~ 1 + log_funding", data=df_iv).fit()
iv  = IV2SLS.from_formula(
        "log_valuation ~ 1 + [log_funding ~ fund_size_max + fund_deals_max]",
        data=df_iv
      ).fit(cov_type="robust")

# Compare
cmp = compare({"OLS": ols, "IV": iv})
print(cmp)

# Wu-Hausman statistic test
# Regress the endogenous variable on the instruments
first_stage = sm.OLS(df_iv["log_funding"], sm.add_constant(df_iv[["fund_size_max", "fund_deals_max"]])).fit()

# Recording of residuals (what the instruments do not explain)
df_iv["residuals_iv"] = first_stage.resid

# OLS regression of the structural model + residuals
wu_hausman_test = sm.OLS(
    df_iv["log_valuation"],
    sm.add_constant(df_iv[["log_funding", "residuals_iv"]])
).fit(cov_type='HC3')

print(wu_hausman_test.summary2(float_format="%.4f"))

# Re-estimate the IV model (2SLS)
iv_model = IV2SLS.from_formula(
    "log_valuation ~ 1 + [log_funding ~ fund_size_max + fund_deals_max]",
    data=df_iv
).fit(cov_type="robust")

# Retrieve the residuals from the IV model
df_iv["iv_resid"] = iv_model.resids

# Regress the residuals on all instruments (including the constant)
sargan_test = sm.OLS(df_iv["iv_resid"], sm.add_constant(df_iv[["fund_size_max", "fund_deals_max"]])).fit()

# Compute the Sargan test statistic
n = df_iv.shape[0]  # number of observations
R2 = sargan_test.rsquared
sargan_stat = n * R2

# Compute the p-value (chi-square test with k-1 degrees of freedom)
df = df_iv[["fund_size_max", "fund_deals_max"]].shape[1] - 1  # nb of instruments - nb of endogenous variables
p_value = 1 - chi2.cdf(sargan_stat, df)

print("=== Sargan Test for Overidentifying Restrictions ===")
print(f"Sargan statistic: {sargan_stat:.3f}")
print(f"Degrees of freedom: {df}")
print(f"P-value: {p_value:.4f}")

if p_value > 0.05:
    print("\n Instruments are exogenous (fail to reject H0).")
else:
    print("\n Instruments may be endogenous (reject H0).")